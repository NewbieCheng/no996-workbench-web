/** 返回面向用户的中文镜头名称；原始 name 仍用于稳定 ID 与数据交换。 */
export function getShotDisplayName(shot: Pick<ShotDefinition, 'name'>): string {
  const exact = SHOT_LABELS[shot.name]
  if (exact) return exact

  const translated = shot.name
    .split('-')
    .map((word) => WORDS[word] ?? word)
    .join('')
  return translated || '视频镜头'
}

export function getShotCategoryDisplayName(
  shot: Pick<ShotDefinition, 'category' | 'categoryLabel'>,
): string {
  return CATEGORY_LABELS[shot.category] ?? shot.categoryLabel
}

export function getShotAccessibleLabel(shot: ShotDefinition): string {
  return `${getShotCategoryDisplayName(shot)}：${getShotDisplayName(shot)}，时长 ${(shot.durationInFrames / 30).toFixed(1)} 秒`
}
